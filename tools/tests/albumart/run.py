#!/usr/bin/env python3
"""Portable artwork regression entry point; output stays outside the checkout."""
import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source-root', type=Path, default=Path(__file__).resolve().parents[3])
parser.add_argument('--output', type=Path)
parser.add_argument('--only', choices=['decode', 'resolver', 'metadata', 'flows'])
args = parser.parse_args()
output = args.output or Path(tempfile.mkdtemp(prefix='albumart-tests-'))
output = output.resolve()
output.mkdir(parents=True, exist_ok=True)
env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', ART_TEST_ROOT=str(args.source_root.resolve()), ART_TEST_OUT=str(output))
print('Artwork test output:', output, flush=True)
failed = []
for suite in ['decode', 'resolver', 'metadata', 'flows']:
    if args.only and args.only != suite:
        continue
    # Resolver links the decoder objects generated by decode.py.
    result = subprocess.run([sys.executable, str(Path(__file__).with_name(suite + '.py'))], env=env)
    if result.returncode:
        failed.append(suite)
if failed:
    sys.exit('FAIL: ' + ', '.join(failed))
print('PASS: all selected artwork suites')
